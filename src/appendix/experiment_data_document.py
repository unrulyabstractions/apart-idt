"""One run's whole data appendix, assembled and given its own label namespace.

Both runs are generated by the same code from the same six stages, so both
carry the same section, table, and figure labels. Each document is therefore
passed through the namespacer before it is written, and the primary run also
keeps the unsuffixed labels because the body sections cite them and are not
generated. Stages that have not finished render as pending rows inside their
own tables rather than vanishing, so the appendix always accounts for every run
directory the pipeline would write.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from src.appendix.run_directory_inventory import inventory_table
from src.appendix.run_label_namespacing import namespace_labels
from src.appendix.stage_collection_tables import collection_section
from src.appendix.stage_comparison_tables import comparison_section
from src.appendix.stage_conjecture_cards import conjecture_section
from src.appendix.stage_elicitation_tables import elicitation_section
from src.appendix.stage_promptset_cards import promptset_section
from src.appendix.stage_scoring_tables import scoring_section

__all__ = ["latest_artifact_time", "experiment_data_document"]


def latest_artifact_time(out_root) -> str:
    """When the newest artifact under this tree was written.

    A rerun still in flight grows while the appendix is generated, so the
    document states which snapshot of the tree it read rather than implying the
    counts are final.
    """
    newest = 0.0
    for path in Path(out_root).rglob("*"):
        if path.is_file():
            newest = max(newest, path.stat().st_mtime)
    return datetime.fromtimestamp(newest).strftime("%Y-%m-%d %H:%M") if newest else "no artifact"


def experiment_data_document(out_root, run_key: str, run_label: str, primary: bool = False,
                             sibling_key: str = "", sibling_label: str = "",
                             scope_note: str = "") -> str:
    """The full ``\\section`` for one run, namespaced and ready to ``\\input``."""
    root = Path(out_root)
    pointer = ""
    if sibling_key:
        pointer = (f" The {sibling_label} is in \\autoref{{app:data-{sibling_key}}}; the two are "
                   "generated by the same code from the same six stages, so their tables carry "
                   "the same columns and can be read side by side.")
    body = "\n".join([
        f"\\section{{Experiment data: {run_label}}}",
        "\\label{app:data}",
        "",
        f"Everything this run's pipeline produced, read out of \\texttt{{{root}/}} at "
        f"{latest_artifact_time(root)}. One subsection per stage, in pipeline order: principal "
        "elicitation, prompt set construction, hypothesis conjecture, response collection, "
        "response scoring, and comparing distributions. Every number is read from the "
        "artifacts by \\texttt{script/paper/write\\_data\\_appendix.py}, and every quoted "
        f"prompt, reply, and hypothesis is verbatim.{pointer}",
        "",
        "The inventory below lists every run directory this pipeline writes, so anything "
        "absent from the data is visible here rather than missing from the appendix. A stage "
        "that had not finished would appear as a marked row; every stage of every reported "
        "run has finished, so no such row appears.",
        "",
        scope_note,
        "" if not scope_note else "",
        "\\subsection{What ran}",
        "\\label{app:data-inventory}",
        "",
        inventory_table(root),
        "",
        "\\clearpage", "%-----------------------------------",
        elicitation_section(root), "",
        "\\clearpage", "%-----------------------------------",
        promptset_section(root), "",
        "\\clearpage", "%-----------------------------------",
        conjecture_section(root), "",
        "\\clearpage", "%-----------------------------------",
        collection_section(root), "",
        "\\clearpage", "%-----------------------------------",
        scoring_section(root), "",
        "\\clearpage", "%-----------------------------------",
        comparison_section(root, run_key), "",
    ])
    header = ("% Generated by script/paper/write_data_appendix.py. Do not edit by hand:\n"
              f"% rerun the script so the appendix matches the artifacts in {root}/.\n")
    return header + namespace_labels(body, run_key, keep_bare=primary)
